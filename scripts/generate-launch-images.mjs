// Generates the iPhone launch screens shown while Jern opens from the Home Screen,
// and writes the matching <link rel="apple-touch-startup-image"> tags into index.html.
// iOS only shows an image whose size exactly matches the device, so each screen
// size needs its own file. Run with `npm run generate:launch-images` after
// changing the mark or colours, or to add new iPhone sizes.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const root = fileURLToPath(new URL('..', import.meta.url));
const outputDirectory = `${root}public/launch`;
const indexPath = `${root}index.html`;

// Matches the dark default theme (theme-color and --default-background) and the app icon.
const background = '#111a14';
const markPath = 'M46 4h54v62c0 22-14 34-36 34H22L0 72h65c5 0 7-3 7-8V30H26Z';
const markColor = '#9ac39d';
const markWidth = 96;

// Portrait CSS size and pixel ratio of each iPhone screen.
const screens = [
  { width: 320, height: 568, ratio: 2, devices: 'iPhone SE (1st generation)' },
  { width: 375, height: 667, ratio: 2, devices: 'iPhone 6–8, SE (2nd and 3rd generation)' },
  { width: 414, height: 736, ratio: 3, devices: 'iPhone 6–8 Plus' },
  { width: 375, height: 812, ratio: 3, devices: 'iPhone X, XS, 11 Pro, 12 mini, 13 mini' },
  { width: 414, height: 896, ratio: 2, devices: 'iPhone XR, 11' },
  { width: 414, height: 896, ratio: 3, devices: 'iPhone XS Max, 11 Pro Max' },
  { width: 390, height: 844, ratio: 3, devices: 'iPhone 12, 12 Pro, 13, 13 Pro, 14, 16e' },
  { width: 428, height: 926, ratio: 3, devices: 'iPhone 12 Pro Max, 13 Pro Max, 14 Plus' },
  { width: 393, height: 852, ratio: 3, devices: 'iPhone 14 Pro, 15, 15 Pro, 16' },
  { width: 430, height: 932, ratio: 3, devices: 'iPhone 14 Pro Max, 15 Plus, 15 Pro Max, 16 Plus' },
  { width: 402, height: 874, ratio: 3, devices: 'iPhone 16 Pro, 17, 17 Pro' },
  { width: 420, height: 912, ratio: 3, devices: 'iPhone Air' },
  { width: 440, height: 956, ratio: 3, devices: 'iPhone 16 Pro Max, 17 Pro Max' },
];

const page = (width, height) => `<!doctype html><html><body style="margin:0;width:${width}px;height:${height}px;display:grid;place-items:center;background:${background}">
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 104 100" width="${markWidth}" height="${Math.round(markWidth * 100 / 104)}"><path fill="${markColor}" d="${markPath}"/></svg>
</body></html>`;

const browser = await chromium.launch();
const links = [];
try {
  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });
  for (const screen of screens) {
    for (const orientation of ['portrait', 'landscape']) {
      const [width, height] = orientation === 'portrait' ? [screen.width, screen.height] : [screen.height, screen.width];
      const file = `launch-${width * screen.ratio}x${height * screen.ratio}.png`;
      const context = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: screen.ratio });
      const tab = await context.newPage();
      await tab.setContent(page(width, height));
      await tab.screenshot({ path: `${outputDirectory}/${file}`, type: 'png' });
      await context.close();
      if (orientation === 'portrait') links.push(`    <!-- ${screen.devices} -->`);
      links.push(`    <link rel="apple-touch-startup-image" media="screen and (device-width: ${screen.width}px) and (device-height: ${screen.height}px) and (-webkit-device-pixel-ratio: ${screen.ratio}) and (orientation: ${orientation})" href="/launch/${file}" />`);
    }
  }
} finally {
  await browser.close();
}

const start = '    <!-- launch-images:start (generated by scripts/generate-launch-images.mjs) -->';
const end = '    <!-- launch-images:end -->';
const html = await readFile(indexPath, 'utf8');
const block = [start, ...links, end].join('\n');
const existing = new RegExp(`${start.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${end.trim()}`);
const updated = existing.test(html)
  ? html.replace(new RegExp(`[ \\t]*${existing.source}`), block)
  : html.replace('    <link rel="manifest"', `${block}\n    <link rel="manifest"`);
if (updated === html && !existing.test(html)) throw new Error('Could not find where to add launch images in index.html.');
await writeFile(indexPath, updated);
console.log(`Wrote ${links.length - screens.length} launch images to public/launch and updated index.html.`);
